#!/bin/sh
# Regenerates BOARD.md from each task file's frontmatter. Run after changing status/claimed-by.
cd "$(dirname "$0")" || exit 1
{
  echo "# GOS backport — board"
  echo
  echo "Generated by board.sh on $(date '+%Y-%m-%d %H:%M'). Edit task frontmatter, not this file."
  echo
  echo "| Task | Phase | Status | Claimed by | Depends on | Commit |"
  echo "|---|---|---|---|---|---|"
  for f in [0-9][0-9]-*.md; do
    [ "$f" = 00-overview.md ] && continue
    awk -v file="$f" '
      /^---$/ { n++; next }
      n == 1 { i = index($0, ":"); k = substr($0, 1, i - 1); v[k] = substr($0, i + 1); sub(/^ +/, "", v[k]) }
      n == 2 { exit }
      END { printf "| %s %s | %s | %s | %s | %s | %s |\n", v["task"], v["title"], v["phase"], v["status"], v["claimed-by"], v["depends-on"], v["commit"] }
    ' "$f"
  done
} > BOARD.md
cat BOARD.md
